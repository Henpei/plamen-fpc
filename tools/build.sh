#!/usr/bin/env bash
# Stamps src/version.inc with the current git commit hash (build-time only).
# If git is unavailable we stamp "nogit" and WARN loudly on stderr (build
# metadata, not game data; runtime never silently falls back).
set -u
cd "$(dirname "$0")/.."
HASH="$(git rev-parse --short HEAD 2>/dev/null || true)"
if [ -z "$HASH" ]; then
  echo "build.sh: WARNING: git hash unavailable, stamping 'nogit'" >&2
  HASH="nogit"
fi
DATE="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
cat > src/version.inc <<EOF
  { generated by tools/build.sh — do not edit }
  PLAMEN_COMMIT = '$HASH';
  PLAMEN_BUILDTIME = '$DATE';
EOF
echo "build.sh: stamped version.inc commit=$HASH built=$DATE"
